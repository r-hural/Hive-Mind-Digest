"""Bundled example source list and its sample report for /hmd:init (IDEA-042).

examples/samples/claude-code-fundamentals/summary.md is the example list's report, recorded on the
0.1 pipeline (it bills the API once); the report-shaped test below skips only while it is absent.
"""
import pathlib
import re

import pytest

from pipeline.stages.fetch import parse_youtube_url, read_url_file
from tests.helpers import skill_files

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
EXAMPLES_DIR = REPO_ROOT / "examples"
EXAMPLE_LIST = EXAMPLES_DIR / "claude-code-fundamentals.txt"
SAMPLE_DIGEST = EXAMPLES_DIR / "samples" / "claude-code-fundamentals" / "summary.md"
SKILL_PATH = skill_files()["init"]

# pipeline/stages/output.py::fmt_time renders "m:ss" or "h:mm:ss" (h/m unpadded, mm/ss
# zero-padded) -- this matches either shape at the end of an attribution string.
_TIME_RE = re.compile(r"\d+:\d{2}(:\d{2})?$")
_EM_DASH = "\u2014"


def test_example_list_urls_are_parseable_unique_and_countable():
    urls = read_url_file(str(EXAMPLE_LIST))
    assert 5 <= len(urls) <= 10
    assert len(urls) == 6
    assert len(set(urls)) == len(urls)                                # no duplicate URLs
    assert len({parse_youtube_url(u) for u in urls}) == len(urls)     # no duplicate videos


def test_example_list_has_no_placeholder_and_correct_url_form():
    # Every URL in the shipped file uses the same https://www.youtube.com/watch?v=<id> form.
    # That's a uniformity rule for this file, not a pipeline constraint -- parse_youtube_url
    # itself also accepts youtu.be, /shorts/, /embed/ and other YouTube URL shapes.
    text = EXAMPLE_LIST.read_text(encoding="utf-8")
    assert "REPLACE_ME" not in text
    for url in read_url_file(str(EXAMPLE_LIST)):
        assert url.startswith("https://www.youtube.com/watch?v="), url
        video_id = url.rsplit("=", 1)[1]
        assert len(video_id) == 11, url


def test_skill_references_the_example_files_and_matching_count():
    skill_text = SKILL_PATH.read_text(encoding="utf-8")
    assert "examples/claude-code-fundamentals.txt" in skill_text
    assert "examples/samples/claude-code-fundamentals/summary.md" in skill_text
    assert not (EXAMPLES_DIR / "sample-digest.md").exists()          # replaced by examples/samples/
    assert EXAMPLE_LIST.exists()
    m = re.search(r"(\d+) public Anthropic videos", skill_text)
    assert m, "skill wording must state the count as '<N> public Anthropic videos'"
    assert int(m.group(1)) == len(read_url_file(str(EXAMPLE_LIST)))


@pytest.mark.skipif(not SAMPLE_DIGEST.exists(), reason="sample not recorded yet")
def test_sample_digest_quotes_are_short_and_attributed():
    text = SAMPLE_DIGEST.read_text(encoding="utf-8")
    assert text.startswith("> Sample output generated by") and "## TL;DR" in text and "&t=" in text
    # pipeline/stages/output.py::render_markdown joins a show_anchors quote line as
    # '  > "<quote>" -- <title> <time>' using an em dash (U+2014) separator, and a claim's quote
    # is 8-40 words per pipeline/prompts/analyze.py -- check the quote itself, not the whole line.
    sep = f'" {_EM_DASH} '
    for line in text.splitlines():
        if line.startswith("  > "):
            parts = line[4:].rsplit(sep, 1)
            assert len(parts) == 2, line            # attribution present
            quote, attribution = parts
            assert quote.startswith('"'), line
            assert len(quote.split()) <= 40, line   # matches the analyze prompt's 8-40 word rule
            assert _TIME_RE.search(attribution), line   # ends in m:ss or h:mm:ss (fmt_time)
    readme_text = (EXAMPLES_DIR / "README.md").read_text(encoding="utf-8")
    assert "2026-MM-DD" not in readme_text          # recording the digest replaces the placeholder date
