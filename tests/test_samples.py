"""The shipped sample reports under examples/samples/ (Public Preview 0.1): every file carries the
model-output banner, no rendered quote is over 40 words, and together the samples show every report
element. Reads only examples/; skips while the samples are not collected yet."""
from __future__ import annotations

import pathlib
import re

import pytest

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
SAMPLES_DIR = REPO_ROOT / "examples" / "samples"
SAMPLE_NAMES = ("claude-code-best-practices", "claude-code-fundamentals", "micro-habits",
                "micro-habits-mixed", "productivity")
FORMATS = ("summary", "digest", "hybrid", "outline", "quotes")
WITH_DIFF = ("claude-code-best-practices",)
BANNER_PREFIX = "> Sample output generated by Hive Mind Digest"
MAX_QUOTE_WORDS = 40
# Each must appear in a body line of some sample (the badge legend and the banner do not count).
# "(may differ by edition or date)" is not required: none of the 0.1 sample notebooks has a
# contradiction the check labels that way (owner, 2026-10-26: ship without it).
ELEMENTS = ("## Contents", "## Source scorecard", "## Coverage", "## Contradictions", "(confirmed by ",
            "(partly supported)", "(disputed)", "(new)", "_Sources:", "#page=", "#:~:text=")
_QUOTE_LINE = re.compile(r'^\s*> "(.*)"')

pytestmark = pytest.mark.skipif(not SAMPLES_DIR.is_dir(), reason="examples/samples/ not collected yet")


def _sample_files() -> list[pathlib.Path]:
    return sorted(SAMPLES_DIR.rglob("*.md"))


def _body_lines(path: pathlib.Path) -> list[str]:
    return [line for line in path.read_text(encoding="utf-8").splitlines()
            if not line.startswith("_Badges:") and not line.startswith(BANNER_PREFIX)]


def test_every_sample_starts_with_the_banner():
    files = _sample_files()
    assert files
    bad = [p.relative_to(SAMPLES_DIR).as_posix() for p in files
           if not p.read_text(encoding="utf-8").startswith(BANNER_PREFIX)]
    assert not bad, bad


def test_no_rendered_quote_is_over_40_words():
    long = []
    for path in _sample_files():
        for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
            m = _QUOTE_LINE.match(line)
            if m:
                quote = m.group(1).split('" — ')[0]
                if len(quote.split()) > MAX_QUOTE_WORDS:
                    long.append(f"{path.relative_to(SAMPLES_DIR).as_posix()}:{lineno}")
    assert not long, long


def test_each_collected_sample_has_every_format():
    present = [d for d in SAMPLES_DIR.iterdir() if d.is_dir()]
    assert present
    for d in present:
        assert d.name in SAMPLE_NAMES, d.name
        wanted = FORMATS + (("diff",) if d.name in WITH_DIFF else ())
        missing = [f for f in wanted if not (d / f"{f}.md").is_file()]
        assert not missing, (d.name, missing)


def test_samples_together_show_every_element():
    missing_samples = [n for n in SAMPLE_NAMES if not (SAMPLES_DIR / n).is_dir()]
    if missing_samples:
        pytest.skip(f"not all samples collected yet: {missing_samples}")
    text = "\n".join(line for p in _sample_files() for line in _body_lines(p))
    absent = [e for e in ELEMENTS if e not in text]
    assert not absent, absent


_FORBIDDEN_IN_HTML = ("<script", "<link ", "<iframe", "<img", "@import", "url(")


def test_every_markdown_sample_has_an_html_twin():
    missing = [p.relative_to(SAMPLES_DIR).as_posix() for p in _sample_files()
               if not p.with_suffix(".html").is_file()]
    assert not missing, missing


def test_html_samples_have_banner_are_self_contained_and_cap_quotes():
    pages = sorted(SAMPLES_DIR.rglob("*.html"))
    assert pages
    for path in pages:
        text = path.read_text(encoding="utf-8")
        name = path.relative_to(SAMPLES_DIR).as_posix()
        assert 'class="sample-banner"' in text, name
        assert text.count('<style id="hmd-theme">') == 1 and text.count("<style") == 1, name
        assert "<!-- hmd:theme:start -->" in text and "<!-- hmd:theme:end -->" in text, name
        assert not re.search(r"\sstyle=", text), name
        low = text.lower()
        assert not [bad for bad in _FORBIDDEN_IN_HTML if bad in low], name
        assert not re.search(r'src="https?:', text), name
        long = [q for q in re.findall(r'<q class="quote">(.*?)</q>', text) if len(q.split()) > MAX_QUOTE_WORDS]
        assert not long, (name, long[:1])


def test_html_sample_report_links_resolve():
    for path in sorted(SAMPLES_DIR.rglob("*.html")):
        text = path.read_text(encoding="utf-8")
        for target in re.findall(r'href="([^"#:]+\.html)"', text):
            assert (path.parent / target).is_file(), (path.relative_to(SAMPLES_DIR).as_posix(), target)
